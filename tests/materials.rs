#[test]
fn authored_line_arrays_preserve_integer_values_and_original_material_bytes() {
    // SPEC-BLT-005: the actual tag parser delivers arrays to include unchanged.
    let root = tempfile::tempdir().unwrap();
    fs::write(
        root.path().join("guide.md"),
        "{% include 'notes.txt' lines=[1e0,2.0] %}\n{% include 'notes.txt' lines='1-2' %}\n",
    )
    .unwrap();
    fs::write(root.path().join("notes.txt"), "First\r\n末尾").unwrap();
    let output = Command::new(env!("CARGO_BIN_EXE_source-down"))
        .args(["render", "guide.md", "--root"])
        .arg(root.path())
        .output()
        .unwrap();
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    let page = fs::read_to_string(root.path().join(".source-down/pages/guide.md.md")).unwrap();
    assert_eq!(page.matches("First\r\n末尾\n\n").count(), 2);
    assert_eq!(
        page.matches("[`notes.txt:L1-L2`](../../notes.txt#L1) · bytes [0,13)")
            .count(),
        2
    );
}

